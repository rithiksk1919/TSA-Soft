// Buttons and the room glide on the hub: rest, mid-swoosh, settled, button hover, toggles.
import { chromium } from "playwright";
const b = await chromium.launch({ headless: true });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://127.0.0.1:8000/");
await p.waitForSelector(".school .room .cam3", { state: "attached" });
await p.waitForTimeout(1200);
await p.screenshot({ path: "qa/extension/btn-0-rest.png" });
const room = async (id) => p.locator('.room[data-room="' + id + '"]').boundingBox();
const c = await room("classroom");
await p.mouse.move(c.x + c.width / 2, c.y + c.height / 2);
await p.waitForTimeout(700);
const l = await room("lunch");
await p.mouse.move(l.x + l.width / 2, l.y + l.height / 2);
await p.waitForTimeout(140);
const box = await p.locator(".school").boundingBox();
await p.screenshot({ path: "qa/extension/btn-1-swoosh.png", clip: box });
await p.waitForTimeout(900);
await p.screenshot({ path: "qa/extension/btn-2-settled.png", clip: box });
const ring = await p.evaluate(() => { const r = document.querySelector(".glide:not(.glide--echo)").getBoundingClientRect(); const t = document.querySelector('.room[data-room="lunch"]').getBoundingClientRect(); return [Math.round(r.x - t.x), Math.round(r.y - t.y), Math.round(r.width - t.width)]; });
console.log("frame offset from lunchroom (x, y, width):", ring.join(", "));
await p.hover("#go-next");
await p.waitForTimeout(250);
await p.screenshot({ path: "qa/extension/btn-3-hover.png", clip: { x: 0, y: 0, width: 1600, height: 230 } });
await p.click("#view-classic");
await p.waitForTimeout(150);
await p.screenshot({ path: "qa/extension/btn-4-toggle-mid.png", clip: { x: 900, y: 0, width: 700, height: 70 } });
await p.waitForTimeout(700);
await p.click("#view-school");
await p.waitForTimeout(900);
await p.click('.mistakes .seg button[data-scope="all"]');
await p.waitForTimeout(600);
await p.screenshot({ path: "qa/extension/btn-5-after.png" });
await p.keyboard.press("Tab");
await p.goto("http://127.0.0.1:8000/#/classroom");
await p.waitForTimeout(1500);
await p.screenshot({ path: "qa/extension/btn-6-classroom.png", clip: { x: 0, y: 0, width: 1600, height: 300 } });
console.log(errs.join("\n") || "no errors");
await b.close();
