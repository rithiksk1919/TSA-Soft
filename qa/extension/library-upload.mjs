// Your subjects in the library: upload a folder of subjects, see them on the room's bookcase,
// open one. Test subjects are deleted at the end (they live in data/uploads/).
import { chromium } from "playwright";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "sb-up-"));
const school = path.join(root, "School");
const put = (rel, body) => { const p = path.join(school, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, body); };
put("Test Math/Unit 1/linear equations.md", "# Linear equations\n\nTo solve 2x + 3 = 11, subtract 3 from both sides, then divide by 2: x = 4.\n");
put("Test Math/Unit 1/practice set.txt", "1. 3x - 5 = 10\n2. 4(x + 1) = 20\n");
put("Test Math/Unit 2/fractions.txt", "Add 3/4 + 1/2 by finding a common denominator: 3/4 + 2/4 = 5/4.\n");
put("Test Math/syllabus.docx", "not really a docx");
put("Test Biology/cells.txt", "The cell membrane controls what enters and leaves the cell.\n");
const B = "http://127.0.0.1:8000";
const b = await chromium.launch({ headless: true });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(B + "/library/");
await p.waitForTimeout(1500);
await p.click('.rnav__btn[data-station="learn"]');
await p.waitForTimeout(1800);
await p.screenshot({ path: "qa/extension/lib-0-shelf.png" });
await p.click(".rbooks__btn--add");
await p.waitForSelector("dialog.up[open]");
await p.screenshot({ path: "qa/extension/lib-1-dialog.png" });
await p.setInputFiles("#up-dir", school);
await p.waitForSelector("#up-preview:not([hidden])");
await p.screenshot({ path: "qa/extension/lib-2-preview.png" });
await p.click('[data-act="go"]');
await p.waitForFunction(() => /Added/.test(document.querySelector("#up-status").textContent), null, { timeout: 20000 });
await p.screenshot({ path: "qa/extension/lib-3-added.png" });
console.log("status:", await p.textContent("#up-status"));
await p.click(".up__close");
await p.waitForTimeout(600);
await p.screenshot({ path: "qa/extension/lib-4-shelf-mine.png" });
const books = await p.$$eval(".book3--mine", (n) => n.map((x) => x.getAttribute("data-book")));
console.log("books in your section:", books.join(", "));
await p.click('.rbooks__btn--mine[data-book="my-test-math"]');
await p.waitForTimeout(3500);
await p.screenshot({ path: "qa/extension/lib-5-open.png" });
await p.locator(".mf", { hasText: "linear equations.md" }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: "qa/extension/lib-6-file.png" });
console.log(errs.join("\n") || "no page errors");
await b.close();
for (const id of ["test-math", "test-biology"]) await fetch(B + "/api/my-subjects/" + id, { method: "DELETE" }).catch(() => {});
fs.rmSync(root, { recursive: true, force: true });
