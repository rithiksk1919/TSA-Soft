import { chromium } from "@playwright/test";
const b = await chromium.launch(); const errs = [];
const p = await b.newPage({ viewport: { width: 1360, height: 860 } });
p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://127.0.0.1:5180/"); await p.waitForTimeout(1500);
const st = () => p.evaluate(() => ({ room: window.SkillBridge.room.state(), book: window.SkillBridge.bookOpen(), drawer: window.SkillBridge.debug.drawer() }));
await p.click('.rnav__btn[data-station="learn"]'); await p.waitForTimeout(1600);
await p.screenshot({ path: "qa/traces/ir-1-learn.png" });
await p.click('.rbooks__btn[data-book="chemistry"]'); await p.waitForTimeout(500);
await p.screenshot({ path: "qa/traces/ir-2-pull.png" }); await p.waitForTimeout(500);
await p.screenshot({ path: "qa/traces/ir-3-opening.png" }); await p.waitForTimeout(1800);
await p.screenshot({ path: "qa/traces/ir-4-open.png" }); console.log("open", JSON.stringify(await st()));
await p.keyboard.press("Escape"); await p.waitForTimeout(1600);
await p.screenshot({ path: "qa/traces/ir-5-closed.png" }); console.log("closed", JSON.stringify(await st()));
await p.keyboard.press("Escape"); await p.waitForTimeout(1600);
await p.click('.rnav__btn[data-station="practice"]'); await p.waitForTimeout(1800);
await p.screenshot({ path: "qa/traces/ir-6-practice.png" }); console.log("practice", JSON.stringify(await st()));
await p.click('.dslot[data-id="index"] .drawer'); await p.waitForTimeout(1500);
await p.screenshot({ path: "qa/traces/ir-7-drawer.png" }); await p.waitForTimeout(1500);
await p.screenshot({ path: "qa/traces/ir-8-panel.png" });
await p.keyboard.press("Escape"); await p.waitForTimeout(2600);
await p.keyboard.press("Escape"); await p.waitForTimeout(1600); console.log("out", JSON.stringify(await st()));
console.log("errors", JSON.stringify(errs)); await b.close();
